"""What a capture found, read back from its database and indexed by URL.

The results live in gowitness's own SQLite database. That is what an externally
run capture leaves behind - the documented workflow is `scan file --write-db`,
with no JSON Lines file at all - and it is what the application already writes
for the report server, so it is the one source that is present however the
capture was produced. It also holds two things nothing else does: the row id the
report server addresses results by (the JSON Lines writer sets every `id` to
`0`), and the full header, cookie, console and certificate detail.

**The schema is not a published interface.** It is generated by the tool's ORM
and can differ between versions, so nothing here names a fixed column list.
Tables and columns are looked up first and only what exists is read; an optional
table that is absent is empty data, not an error. What cannot be read is
reported on `Captures.problems` rather than raised, because a viewer that
refuses to start over one unreadable capture is worse than one that says so and
carries on.

**The database is opened read-only.** A capture may be running and writing to it
while the viewer reads, and the viewer has no business writing to it ever.

**Failures are not in here.** gowitness records nothing at all for a target it
could not load, so a failed URL is knowable only from the run's log while the
run is in hand (`capture.CaptureRun.failures`, fed in through `add_failures`).
The absence of a URL in a database is therefore not evidence that it succeeded.
"""

from __future__ import annotations

import sqlite3
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import urlsplit

_DEFAULT_PORT = {"http": 80, "https": 443}


def canonical_url(url: str) -> str:
    """`scheme://host:port`, with the default port made explicit.

    Captures are joined to services by URL, and the two sides spell the same
    address differently. `export_urls` omits a default port, as a URL should:
    `http://fritz.box`. gowitness records what it *probed*, and it probes the
    port set - so the same page comes back as `http://fritz.box:80`. Measured:
    two port-less URLs produced four recorded results, none of which matched
    the URL they came from, which is why nothing linked.

    Both sides go through here, so the join no longer depends on either of them
    spelling it the same way.
    """
    if not url:
        return url
    split = urlsplit(url)
    if not split.scheme or not split.hostname:
        return url.rstrip("/")
    port = split.port or _DEFAULT_PORT.get(split.scheme.lower())
    host = split.hostname
    if port is None:
        return f"{split.scheme}://{host}".rstrip("/")
    return f"{split.scheme}://{host}:{port}"

# Looked for by name so that their *absence* can be reported. A missing
# security header cannot be noticed by reading the headers that are present,
# which is the whole reason to name them; this is a list of what was checked,
# not a judgement about what a server ought to send.
SECURITY_HEADERS: tuple[tuple[str, str], ...] = (
    ("strict-transport-security", "hsts"),
    ("content-security-policy", "csp"),
    ("x-frame-options", "x-frame-options"),
    ("x-content-type-options", "x-content-type-options"),
    ("referrer-policy", "referrer-policy"),
)

# Headers that tend to name the product behind a page when the technology
# detector found nothing.
_NAMING_HEADERS = ("server", "x-powered-by", "x-generator", "x-authentik-id",
                   "x-drupal-cache", "x-shopify-stage")


@dataclass(slots=True)
class Capture:
    """One captured URL: what answered, and where the picture of it is."""

    url: str
    row_id: int | None = None            # how the report server addresses it
    final_url: str = ""
    status: int | None = None
    reason: str = ""
    title: str = ""
    protocol: str = ""
    probed_at: str = ""
    content_length: int | None = None
    perception_group: int | None = None
    technologies: list[str] = field(default_factory=list)
    headers: list[tuple[str, str]] = field(default_factory=list)
    cookies: list[tuple[str, str]] = field(default_factory=list)
    console: list[tuple[str, str]] = field(default_factory=list)
    network: list[tuple[str, str]] = field(default_factory=list)
    tls: str = ""
    sans: list[str] = field(default_factory=list)
    shot: Path | None = None
    failure: str = ""

    @property
    def failed(self) -> bool:
        return bool(self.failure)

    @property
    def redirected(self) -> bool:
        """Whether the final URL is somewhere other than the one asked for."""
        return bool(self.final_url) and self.final_url.rstrip("/") != self.url.rstrip("/")

    def header(self, name: str) -> str:
        """A header by name, case-insensitively.

        Case depends on the protocol: HTTP/1.1 keeps whatever the server sent
        (`Content-Type`), HTTP/2 lowercases it as the spec requires. A
        case-sensitive lookup would therefore work on some rows and silently
        fail on others in the same capture.
        """
        wanted = name.lower()
        for key, value in self.headers:
            if key.lower() == wanted:
                return value
        return ""

    @property
    def server(self) -> str:
        return self.header("server")

    @property
    def powered_by(self) -> str:
        return self.header("x-powered-by")

    @property
    def content_type(self) -> str:
        return self.header("content-type").split(";")[0].strip()

    def missing_security_headers(self) -> list[str]:
        """Which of the headers looked for were not sent."""
        present = {key.lower() for key, _ in self.headers}
        return [label for name, label in SECURITY_HEADERS if name not in present]

    def present_security_headers(self) -> list[str]:
        present = {key.lower() for key, _ in self.headers}
        return [label for name, label in SECURITY_HEADERS if name in present]

    def derived_system(self) -> tuple[str, str]:
        """A candidate product name and where it came from, or two empties.

        Only consulted when the technology detector found nothing. Returned with
        its source so it can be labelled: a guess shown as a detection is worse
        than no guess, because the operator cannot tell how far to trust it.
        """
        if self.technologies:
            return "", ""
        for name in _NAMING_HEADERS:
            value = self.header(name)
            if value:
                return value.split("/")[0].strip(), name
        # A title like "FRITZ!Box 7590" names the appliance. One that is just
        # the host it was asked for names nothing - and neither does an error
        # page's title, which is usually its own status line back again.
        title = self.title.strip()
        if not title or title.lower() in self.url.lower():
            return "", ""
        if self.status is not None and title.lower().startswith(str(self.status)):
            return "", ""
        return title, "page title"

    def summary(self) -> str:
        """The one-line description shown under its URL in a record."""
        if self.failed:
            return self.failure
        bits = [f"{self.status} {self.reason}".strip() if self.status else "no status"]
        if self.title:
            bits.append(self.title)
        if self.server:
            bits.append(self.server)
        if self.technologies:
            bits.append(", ".join(self.technologies))
        return " · ".join(bits)


# --- reading the database ------------------------------------------------


def _tables(con: sqlite3.Connection) -> set[str]:
    return {r[0] for r in con.execute(
        "select name from sqlite_master where type='table'")}


def _columns(con: sqlite3.Connection, table: str) -> set[str]:
    return {r[1] for r in con.execute(f"pragma table_info({table})")}


def _rows(con: sqlite3.Connection, table: str, columns: Iterable[str],
          tables: set[str]) -> list[sqlite3.Row]:
    """Select only the columns this database actually has."""
    if table not in tables:
        return []
    have = _columns(con, table)
    wanted = [c for c in columns if c in have]
    if not wanted:
        return []
    return list(con.execute(f"select {', '.join(wanted)} from {table}"))


def _pairs(rows: list[sqlite3.Row], key: str, a: str, b: str
           ) -> dict[int, list[tuple[str, str]]]:
    out: dict[int, list[tuple[str, str]]] = {}
    for row in rows:
        keys = row.keys()
        if key not in keys:
            continue
        out.setdefault(row[key], []).append(
            (str(row[a]) if a in keys else "", str(row[b]) if b in keys else ""))
    return out


def _tls_line(row: sqlite3.Row) -> str:
    keys = row.keys()
    protocol = str(row["protocol"]) if "protocol" in keys and row["protocol"] else ""
    if not protocol:
        return ""
    bits = [protocol]
    for column, prefix in (("cipher", ""), ("issuer", "issued by "),
                           ("valid_to", "until ")):
        if column in keys and row[column]:
            value = str(row[column])
            bits.append(prefix + (value[:10] if column == "valid_to" else value))
    return " · ".join(bits)


def _shot(shots, name: str) -> Path | None:
    if not name or shots is None:
        return None
    return shots(name) if callable(shots) else shots / name


def read_database(path: Path, shots: Path | Callable[[str], Path | None] | None = None
                  ) -> tuple[list[Capture], list[str]]:
    """Every capture in a results database, and a note for what could not be read.

    `shots` is the screenshot directory, or a function from the stored file
    name to where that image actually is (`locate.ShotFinder`) - a capture found
    on disk keeps its images wherever gowitness was run from.

    A missing file is simply no captures: a project that has never been captured
    is the ordinary case, not an error.
    """
    if not path.exists():
        return [], []
    try:
        con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    except sqlite3.DatabaseError as exc:
        return [], [f"{path.name}: {exc}"]
    con.row_factory = sqlite3.Row
    problems: list[str] = []
    try:
        tables = _tables(con)
        if "results" not in tables:
            return [], [f"{path.name}: no results table — not a gowitness database"]

        techs: dict[int, list[str]] = {}
        for row in _rows(con, "technologies", ("result_id", "value"), tables):
            if row["value"]:
                techs.setdefault(row["result_id"], []).append(str(row["value"]))

        headers = _pairs(_rows(con, "headers", ("result_id", "key", "value"), tables),
                         "result_id", "key", "value")
        cookies = _pairs(_rows(con, "cookies", ("result_id", "name", "value"), tables),
                         "result_id", "name", "value")
        console = _pairs(_rows(con, "console_logs", ("result_id", "type", "value"),
                               tables), "result_id", "type", "value")
        # Recorded only when the capture was told to collect everything, so an
        # absent table here is the ordinary case rather than a gap.
        network: dict[int, list[tuple[str, str]]] = {}
        for row in _rows(con, "network_logs",
                         ("result_id", "url", "status_code", "mime_type"), tables):
            keys = row.keys()
            if "result_id" not in keys:
                continue
            status = row["status_code"] if "status_code" in keys else ""
            mime = row["mime_type"] if "mime_type" in keys else ""
            label = " ".join(str(x) for x in (status, mime) if x)
            network.setdefault(row["result_id"], []).append(
                (str(row["url"]) if "url" in keys else "", label))

        sans: dict[int, list[str]] = {}
        for row in _rows(con, "tls_san_lists", ("tls_id", "value"), tables):
            if row["value"]:
                sans.setdefault(row["tls_id"], []).append(str(row["value"]))
        tls_line: dict[int, str] = {}
        tls_sans: dict[int, list[str]] = {}
        for row in _rows(con, "tls", ("id", "result_id", "protocol", "cipher",
                                      "issuer", "valid_to"), tables):
            keys = row.keys()
            if "result_id" not in keys:
                continue
            tls_line[row["result_id"]] = _tls_line(row)
            if "id" in keys:
                tls_sans[row["result_id"]] = sans.get(row["id"], [])

        captures: list[Capture] = []
        for row in _rows(con, "results",
                         ("id", "url", "final_url", "response_code",
                          "response_reason", "protocol", "title", "probed_at",
                          "content_length", "perception_hash_group_id",
                          "filename", "failed", "failed_reason"), tables):
            keys = row.keys()

            def get(name, _keys=keys, _row=row):
                return _row[name] if name in _keys else None

            url = str(get("url") or "")
            if not url:
                continue
            rid = get("id")
            # The column is `filename`; the JSON Lines field was `file_name`.
            # A field-for-field port loses every screenshot path silently.
            name = str(get("filename") or "")
            captures.append(Capture(
                url=url,
                row_id=int(rid) if isinstance(rid, int) else None,
                final_url=str(get("final_url") or ""),
                status=get("response_code") if isinstance(
                    get("response_code"), int) else None,
                reason=str(get("response_reason") or ""),
                title=str(get("title") or ""),
                protocol=str(get("protocol") or ""),
                probed_at=str(get("probed_at") or ""),
                content_length=get("content_length") if isinstance(
                    get("content_length"), int) else None,
                perception_group=get("perception_hash_group_id") if isinstance(
                    get("perception_hash_group_id"), int) else None,
                technologies=techs.get(rid, []),
                headers=headers.get(rid, []),
                cookies=cookies.get(rid, []),
                console=console.get(rid, []),
                network=network.get(rid, []),
                tls=tls_line.get(rid, ""),
                sans=tls_sans.get(rid, []),
                shot=_shot(shots, name),
                failure=str(get("failed_reason") or "") if get("failed") else "",
            ))
        return captures, problems
    except sqlite3.DatabaseError as exc:
        return [], [f"{path.name}: {exc}"]
    finally:
        con.close()


class Captures:
    """Every capture known, indexed by the URL it was taken for.

    One URL can have been captured more than once - a second run over the same
    scope - and the newest wins, because that is what the operator just did.
    """

    def __init__(self, captures: Iterable[Capture] = ()) -> None:
        self._by_url: dict[str, Capture] = {}
        self.problems: list[str] = []
        self.add(captures)

    def __len__(self) -> int:
        return len(self._by_url)

    def __bool__(self) -> bool:
        return bool(self._by_url)

    def add(self, captures: Iterable[Capture]) -> None:
        for capture in captures:
            self._by_url[canonical_url(capture.url)] = capture

    def add_failures(self, failures: dict[str, str]) -> None:
        """Record what a run could not capture - the only source there is."""
        for url, reason in failures.items():
            self._by_url[canonical_url(url)] = Capture(url=url, failure=reason)

    def get(self, url: str) -> Capture | None:
        return self._by_url.get(canonical_url(url))

    def urls(self) -> list[str]:
        """Every URL a capture is known for, as it was recorded."""
        return [c.url for c in self._by_url.values()]

    def for_urls(self, urls: Iterable[str]) -> list[Capture]:
        """The captures for these URLs, in the order given, skipping unknowns.

        One service's URLs can canonicalise to the same key - a scan that found
        both `:80` and the bare form - so a capture is yielded once however many
        ways it was asked for.
        """
        out: list[Capture] = []
        seen: set[str] = set()
        for url in urls:
            key = canonical_url(url)
            found = self._by_url.get(key)
            if found is not None and key not in seen:
                seen.add(key)
                out.append(found)
        return out

    def load(self, path: Path,
             shots: Path | Callable[[str], Path | None] | None = None) -> None:
        captures, problems = read_database(path, shots)
        self.add(captures)
        self.problems.extend(problems)
